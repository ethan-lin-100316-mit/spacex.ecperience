import { test } from 'node:test'
import assert from 'node:assert/strict'
import { initialMission, missionReducer, canStart, canCommand, allChecksComplete, checkDefinitions, flightStages, getTelemetry, getMissionReport } from './missionSequence.js'
const reduce = (state, ...actions) => actions.reduce(missionReducer, state)
const reviewed = state => checkDefinitions.reduce((value, { id }) => value.checks[id] ? value : missionReducer(value, { type: 'CHECK', id }), state)
const armed = state => reduce(reviewed(state), { type: 'POLL' }, { type: 'ARM', value: true })
const ticks = (state, type, count) => { for (let i = 0; i < count; i++) state = missionReducer(state, { type }); return state }
const launch = (missionType = 'deep-space') => ticks(reduce(armed(reduce(initialMission(), { type: 'CONFIGURE', missionType }, { type: 'TERMINAL_PRESET' })), { type: 'START' }), 'TICK', 10)
const checkpoint = state => ticks(state, 'FLIGHT_TICK', flightStages.find(stage => stage.id === state.stage).duration + 2)
const command = (state, name) => missionReducer(state, { type: 'FLIGHT_COMMAND', command: name })
const orbitReady = (missionType = 'deep-space') => checkpoint(command(checkpoint(command(checkpoint(launch(missionType)), 'SEPARATE')), 'INSERT_ORBIT'))

test('six reviews, seven GO stations, poll and arm are all required', () => {
  const initial = initialMission()
  assert.equal(allChecksComplete(initial), false)
  assert.equal(missionReducer(initial, { type: 'START' }).phase, 'standby')
  assert.equal(reduce(initial, { type: 'POLL' }, { type: 'ARM', value: true }).armed, false)
  const noGo = armed(missionReducer(initial, { type: 'STATION', id: 'prop' }))
  assert.equal(canStart(noGo), false)
  assert.equal(missionReducer(noGo, { type: 'START' }).phase, 'standby')
  const ready = armed(initial)
  assert.equal(canStart(ready), true)
  assert.equal(canStart(missionReducer(ready, { type: 'CHECK', id: 'range' })), false)
})
test('station fault holds the countdown and requires recovery, fresh poll and re-arm', () => {
  const running = missionReducer(armed(initialMission()), { type: 'START' })
  const held = reduce(running, { type: 'TICK' }, { type: 'STATION', id: 'gnc' })
  assert.equal(held.phase, 'hold')
  assert.equal(held.holds, 1)
  assert.equal(missionReducer(held, { type: 'TICK' }).countdown, 59)
  const restored = missionReducer(held, { type: 'STATION', id: 'gnc' })
  assert.equal(canStart(restored), false)
  const resumed = missionReducer(armed(restored), { type: 'START' })
  assert.equal(resumed.countdown, 59)
  assert.equal(resumed.phase, 'running')
})
test('manual hold freezes time; preset retains faults and never bypasses preflight', () => {
  const unready = reduce(initialMission(), { type: 'STATION', id: 'prop' }, { type: 'TERMINAL_PRESET' })
  assert.equal(unready.countdown, 10)
  assert.equal(unready.stations.prop, false)
  assert.equal(allChecksComplete(unready), false)
  let state = reduce(armed(initialMission()), { type: 'START' }, { type: 'TICK' }, { type: 'HOLD' })
  assert.equal(state.countdown, 59)
  state = ticks(missionReducer(armed(state), { type: 'START' }), 'TICK', 65)
  assert.equal(state.phase, 'flight')
  assert.equal(state.log.filter(line => line.includes('LIFTOFF')).length, 1)
  assert.equal(state.countdownElapsed, 60)
})
test('mission changes invalidate the flight-plan review and cannot occur in flight', () => {
  const changed = missionReducer(armed(initialMission()), { type: 'CONFIGURE', missionType: 'orbit' })
  assert.equal(changed.checks['flight-plan'], false)
  assert.equal(canStart(changed), false)
  const flying = launch()
  for (const action of [{ type: 'CONFIGURE', missionType: 'orbit' }, { type: 'TERMINAL_PRESET' }, { type: 'CHECK', id: 'range' }, { type: 'STATION', id: 'prop' }]) assert.strictEqual(missionReducer(flying, action), flying)
})
test('flight gates block early or out-of-order commands and freeze at the decision', () => {
  const flying = launch()
  assert.strictEqual(command(flying, 'SEPARATE'), flying)
  const ready = checkpoint(flying)
  assert.equal(canCommand(ready), true)
  assert.equal(ready.stageSeconds, 70)
  assert.equal(ready.flightSeconds, 70)
  assert.strictEqual(command(ready, 'INSERT_ORBIT'), ready)
  assert.strictEqual(missionReducer(ready, { type: 'FLIGHT_TICK' }), ready)
  assert.equal(ready.milestones.filter(item => item.id === 'max-q').length, 1)
  const stage2 = command(ready, 'SEPARATE')
  assert.equal(stage2.stage, 'stage2')
  assert.equal(stage2.stageSeconds, 0)
  assert.strictEqual(command(stage2, 'SEPARATE'), stage2)
})
test('pause and stage-appropriate faults freeze progression until matching recovery', () => {
  const flying = ticks(launch(), 'FLIGHT_TICK', 12)
  const paused = missionReducer(flying, { type: 'PAUSE' })
  assert.strictEqual(missionReducer(paused, { type: 'FLIGHT_TICK' }), paused)
  assert.strictEqual(missionReducer(flying, { type: 'INJECT_FAULT', fault: 'communications' }), flying)
  const failed = missionReducer(paused, { type: 'INJECT_FAULT', fault: 'navigation' })
  assert.equal(failed.fault, 'navigation')
  assert.strictEqual(missionReducer(failed, { type: 'FLIGHT_TICK' }), failed)
  assert.strictEqual(missionReducer(failed, { type: 'RESOLVE_FAULT', resolution: 'backup-link' }), failed)
  const repaired = missionReducer(failed, { type: 'RESOLVE_FAULT', resolution: 'backup-navigation' })
  assert.equal(repaired.fault, null)
  assert.equal(repaired.paused, true)
  assert.equal(repaired.faultsResolved, 1)
  assert.equal(reduce(repaired, { type: 'PAUSE' }, { type: 'FLIGHT_TICK' }).flightSeconds, 13)
})
test('orbital mission includes staging, recovery, orbit insertion and deployment', () => {
  const ready = orbitReady('orbit')
  assert.equal(ready.recovered, true)
  assert.equal(ready.flightSeconds, 220)
  assert.equal(getTelemetry(ready).periapsis, 200)
  const complete = command(ready, 'DEPLOY_PAYLOAD')
  assert.equal(complete.phase, 'complete')
  assert.equal(complete.payloadDeployed, true)
  assert.deepEqual(complete.completedCommands, ['SEPARATE', 'INSERT_ORBIT', 'DEPLOY_PAYLOAD'])
  assert.strictEqual(command(complete, 'DEPLOY_PAYLOAD'), complete)
  assert.strictEqual(missionReducer(complete, { type: 'FLIGHT_TICK' }), complete)
})
test('deep-space mission requires departure, pointing, fault recovery and downlink', () => {
  let state = command(orbitReady(), 'DEPLOY_PAYLOAD')
  assert.equal(state.stage, 'transfer')
  assert.strictEqual(command(state, 'COMMIT_TRANSFER'), state)
  state = checkpoint(command(checkpoint(state), 'COMMIT_TRANSFER'))
  assert.equal(state.stage, 'cruise')
  assert.strictEqual(command(state, 'TRANSMIT_REPORT'), state)
  state = command(state, 'ALIGN_ANTENNA')
  assert.equal(state.antennaAligned, true)
  assert.strictEqual(command(state, 'ALIGN_ANTENNA'), state)
  state = missionReducer(state, { type: 'INJECT_FAULT', fault: 'communications' })
  assert.equal(getTelemetry(state).signal, 0)
  assert.strictEqual(command(state, 'TRANSMIT_REPORT'), state)
  state = missionReducer(state, { type: 'RESOLVE_FAULT', resolution: 'backup-link' })
  state = command(state, 'TRANSMIT_REPORT')
  assert.equal(state.phase, 'complete')
  assert.equal(state.flightSeconds, 325)
  const report = getMissionReport(state)
  assert.equal(report.simulatedElapsedSeconds, 335)
  assert.equal(report.outcome, 'Mission complete')
  assert.equal(report.faultsResolved, 1)
  assert.equal(report.completedChecks.length, 6)
  assert.equal(JSON.parse(JSON.stringify(report)).events.length, state.log.length)
  assert.deepEqual(missionReducer(state, { type: 'RESET' }), initialMission())
})
test('telemetry remains finite and bounded throughout both profiles', () => {
  for (const missionType of ['orbit', 'deep-space']) {
    let state = launch(missionType)
    for (const stage of flightStages) {
      if (state.phase === 'complete') break
      for (let time = 0; time <= stage.duration; time++) {
        const telemetry = getTelemetry(state)
        for (const value of Object.values(telemetry)) assert.ok(value === null || Number.isFinite(value))
        assert.ok(telemetry.propellant >= 0 && telemetry.propellant <= 100)
        assert.ok(telemetry.signal >= 0 && telemetry.signal <= 100)
        assert.ok(telemetry.altitude >= 0)
        state = missionReducer(state, { type: 'FLIGHT_TICK' })
      }
      state = command(state, stage.command)
      if (stage.id === 'cruise') state = command(state, 'TRANSMIT_REPORT')
    }
    assert.equal(state.phase, 'complete')
  }
})
test('unknown controls are ignored and reports cannot mutate simulation state', () => {
  const state = launch()
  assert.strictEqual(missionReducer(state, { type: 'UNKNOWN' }), state)
  const report = getMissionReport(state)
  report.events.push('external edit')
  report.milestones[0].title = 'external edit'
  assert.equal(state.log.includes('external edit'), false)
  assert.notEqual(state.milestones[0].title, 'external edit')
})
